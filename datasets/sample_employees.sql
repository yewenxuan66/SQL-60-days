-- =====================================================================
-- sample_employees.sql  ·  自包含示例库（改编自 MySQL 官方 employees 数据库）
-- 用途：SQL 60 天计划 W1–W4 的练习数据，无需联网下载
-- 规模：8 个部门 / 200 名员工 / 约 300 条薪资记录 / 约 240 条任职记录
-- 导入：mysql -u root -p < sample_employees.sql
-- 注意：为配合练习题，salary 字段用「月薪（元）」口径（4000–16000），
--       与官方库的年薪口径不同，其余表结构与官方一致。
-- =====================================================================
DROP DATABASE IF EXISTS employees;
CREATE DATABASE employees DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE employees;

CREATE TABLE departments (
  dept_id   CHAR(4)     NOT NULL COMMENT '部门编号',
  dept_name VARCHAR(40) NOT NULL COMMENT '部门名称',
  PRIMARY KEY (dept_id),
  UNIQUE KEY uk_dept_name (dept_name)
) ENGINE=InnoDB COMMENT='部门表';

CREATE TABLE employees (
  emp_no      INT         NOT NULL COMMENT '员工编号',
  birth_date  DATE        NOT NULL COMMENT '出生日期',
  first_name  VARCHAR(14) NOT NULL COMMENT '名',
  last_name   VARCHAR(16) NOT NULL COMMENT '姓',
  gender      ENUM('M','F') NOT NULL COMMENT '性别',
  hire_date   DATE        NOT NULL COMMENT '入职日期',
  PRIMARY KEY (emp_no)
) ENGINE=InnoDB COMMENT='员工表';

CREATE TABLE dept_emp (
  emp_no    INT  NOT NULL COMMENT '员工编号',
  dept_id   CHAR(4) NOT NULL COMMENT '部门编号',
  from_date DATE NOT NULL COMMENT '任职开始',
  to_date   DATE NOT NULL COMMENT '任职结束，9999-01-01 表示在职',
  PRIMARY KEY (emp_no, dept_id),
  KEY idx_dept (dept_id)
) ENGINE=InnoDB COMMENT='员工-部门关系表（多对多，含历史）';

CREATE TABLE titles (
  emp_no    INT NOT NULL,
  title     VARCHAR(50) NOT NULL COMMENT '职位',
  from_date DATE NOT NULL,
  to_date   DATE DEFAULT NULL,
  PRIMARY KEY (emp_no, title, from_date)
) ENGINE=InnoDB COMMENT='职位表（含晋升历史）';

CREATE TABLE salaries (
  emp_no    INT NOT NULL,
  salary    INT NOT NULL COMMENT '月薪（元）',
  from_date DATE NOT NULL,
  to_date   DATE DEFAULT NULL,
  PRIMARY KEY (emp_no, from_date)
) ENGINE=InnoDB COMMENT='薪资表（含调薪历史）';

CREATE TABLE dept_manager (
  dept_id   CHAR(4) NOT NULL,
  emp_no    INT     NOT NULL,
  from_date DATE    NOT NULL,
  to_date   DATE    NOT NULL,
  PRIMARY KEY (dept_id, emp_no)
) ENGINE=InnoDB COMMENT='部门经理表';

-- 外键（W3 连接练习会用到，也方便你理解约束）
ALTER TABLE dept_emp     ADD CONSTRAINT fk_de_emp  FOREIGN KEY (emp_no)  REFERENCES employees(emp_no)   ON DELETE CASCADE;
ALTER TABLE dept_emp     ADD CONSTRAINT fk_de_dept FOREIGN KEY (dept_id) REFERENCES departments(dept_id) ON DELETE CASCADE;
ALTER TABLE titles       ADD CONSTRAINT fk_ti_emp  FOREIGN KEY (emp_no)  REFERENCES employees(emp_no)   ON DELETE CASCADE;
ALTER TABLE salaries     ADD CONSTRAINT fk_sa_emp  FOREIGN KEY (emp_no)  REFERENCES employees(emp_no)   ON DELETE CASCADE;
ALTER TABLE dept_manager ADD CONSTRAINT fk_dm_emp  FOREIGN KEY (emp_no)  REFERENCES employees(emp_no)   ON DELETE CASCADE;
ALTER TABLE dept_manager ADD CONSTRAINT fk_dm_dept FOREIGN KEY (dept_id) REFERENCES departments(dept_id) ON DELETE CASCADE;

