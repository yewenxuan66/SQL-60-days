-- ============ D1 验收题的标准答案 ============
-- 题目：从 employees 查 1990 年后入职且薪资 >5000 的姓名，按入职日期倒序取前 5
-- 思路：employees 提供姓名与入职日期；薪资在 salaries 表 → 必须 JOIN；
--       "薪资>5000" 用当前薪资（to_date IS NULL）避免历史记录干扰；
--       倒序取前 5 → ORDER BY hire_date DESC LIMIT 5
SELECT e.first_name, e.last_name, e.hire_date, s.salary
FROM employees e
JOIN salaries s ON s.emp_no = e.emp_no
WHERE e.hire_date >= '1990-01-01'
  AND s.salary > 5000
  AND s.to_date IS NULL          -- 只看当前薪资（★这个条件漏了会算进历史薪资）
ORDER BY e.hire_date DESC
LIMIT 5;

